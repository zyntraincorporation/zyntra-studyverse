// ── Topic Helper Functions ────────────────────────────────────────────────────

/** Get all topics for a specific chapter */
export function getTopicsForChapter(subject, chapterNumber) {
  return TOPIC_DATA[`${subject}_${chapterNumber}`] || [];
}

/** Get count of all topics (including CQ/MCQ/Mock) */
export function getTotalTopicsForChapter(subject, chapterNumber) {
  return getTopicsForChapter(subject, chapterNumber).length;
}

/** Get count of only regular study topics (excludes CQ/MCQ/Mock) */
export function getStudyTopicsForChapter(subject, chapterNumber) {
  return getTopicsForChapter(subject, chapterNumber).filter(t => t.type === 'topic');
}

/** Calculate chapter study progress from topic completion map */
export function calcChapterStudyPct(topics, completionMap) {
  if (!topics || topics.length === 0) return 0;
  const done = topics.filter(t => completionMap?.[t.slug]?.studied).length;
  return Math.round((done / topics.length) * 100);
}

/** Calculate chapter revision progress for a given level (1/2/3) */
export function calcChapterRevisionPct(topics, completionMap, level) {
  if (!topics || topics.length === 0) return 0;
  const key = String(level);
  const done = topics.filter(t => completionMap?.[t.slug]?.revisions?.[key]).length;
  return Math.round((done / topics.length) * 100);
}

